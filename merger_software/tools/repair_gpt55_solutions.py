#!/usr/bin/env python3
"""Repair generic or immediately-failing GPT-5.5 Codeforces solutions.

Targets are regenerated from problem statements only. Existing solution files
are used only for detection/replacement, not as prompt context.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
import threading
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
META = ROOT / "codeforces" / "codeforces_data" / "problems_meta.json"
STATEMENTS = ROOT / "codeforces" / "codeforces_data" / "statements"
OUT = ROOT / "gpt_5.5_sol"
PROGRESS = ROOT / "logs" / "gpt55_repair_progress.json"

CODE_BLOCK = re.compile(r"```(?:python|py)?\s*\n(.*?)```", re.DOTALL | re.I)
BAD_TEXT = re.compile(
    r"(?i)(Generated by|Paradigm:|Rating:.*Tags:|pipeline-generated|"
    r"tail_recursion|search_tree|greedy_recursion|#\s*todo|todo\b|"
    r"fixme\b|stub\b|placeholder\b|left\s+to\s+implement|"
    r"implement\s+me|not\s+implemented)"
)
PRINT_LOCK = threading.Lock()


def pid(problem: dict) -> str:
    return f"{problem['contestId']}{problem['index']}"


def load_meta() -> list[dict]:
    return json.loads(META.read_text())


def compile_ok(path: Path) -> tuple[bool, str]:
    result = subprocess.run(
        [sys.executable, "-m", "py_compile", str(path)],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    return result.returncode == 0, result.stderr.strip()[:500]


def verdict_targets() -> set[str]:
    out: set[str] = set()
    bad_verdicts = {
        "WRONG_ANSWER",
        "RUNTIME_ERROR",
        "IDLENESS_LIMIT_EXCEEDED",
        "TIME_LIMIT_EXCEEDED",
        "MEMORY_LIMIT_EXCEEDED",
        "COMPILATION_ERROR",
    }
    for path in (ROOT / "submissions").glob("*verdicts*.json"):
        try:
            rows = json.loads(path.read_text())
        except Exception:
            continue
        if not isinstance(rows, list):
            continue
        for row in rows:
            if row.get("verdict") in bad_verdicts and row.get("passedTestCount") in (None, 0, 1):
                out.add(row["problem"])
    return out


def detect_targets(problems: list[dict]) -> list[str]:
    targets: list[str] = []
    verdict_bad = verdict_targets()
    for problem in problems:
        name = pid(problem)
        path = OUT / name / "solution.py"
        if not path.exists():
            targets.append(name)
            continue
        text = path.read_text(errors="replace")
        ok, _ = compile_ok(path)
        if BAD_TEXT.search(text) or not ok or name in verdict_bad:
            targets.append(name)
    return targets


def load_done() -> set[str]:
    if not PROGRESS.exists():
        return set()
    try:
        data = json.loads(PROGRESS.read_text())
    except Exception:
        return set()
    return {name for name, rec in data.get("problems", {}).items() if rec.get("status") == "ok"}


def record(name: str, status: str, **extra: object) -> None:
    with PRINT_LOCK:
        try:
            data = json.loads(PROGRESS.read_text()) if PROGRESS.exists() else {}
        except Exception:
            data = {}
        problems = data.setdefault("problems", {})
        problems[name] = {"status": status, "updated": time.strftime("%Y-%m-%d %H:%M:%S"), **extra}
        PROGRESS.parent.mkdir(parents=True, exist_ok=True)
        tmp = PROGRESS.with_suffix(".tmp")
        tmp.write_text(json.dumps(data, indent=2, sort_keys=True))
        tmp.replace(PROGRESS)


def statement_for(problem: dict) -> str:
    data = json.loads((STATEMENTS / f"{problem['contestId']}_{problem['index']}.json").read_text())
    samples = "\n\n".join(
        f"Sample {i} input:\n{s.get('input', '')}\nSample {i} output:\n{s.get('output', '')}"
        for i, s in enumerate(data.get("samples", []), 1)
    )
    return f"""Problem id: {pid(problem)}
Title: {data.get("title") or problem["name"]}
Rating: {problem.get("rating", "unknown")}
Tags: {", ".join(problem.get("tags", []))}
Time limit: {data.get("time_limit", "unknown")}
Memory limit: {data.get("mem_limit", "unknown")}

Statement:
{data.get("statement", "")}

Input:
{data.get("input_spec", "")}

Output:
{data.get("output_spec", "")}

Samples:
{samples or "(none)"}
"""


def prompt(problem: dict) -> str:
    return f"""You are writing a real accepted-style Codeforces Python solution.

Read the problem statement carefully and derive the actual algorithm. Do not
write generic template logic such as summing inputs, subset search, echoing
values, placeholder branches, or guessed behavior. Do not add comments,
metadata headers, ratings, tags, paradigms, or explanations.

Requirements:
- Complete Python 3 / PyPy 3 program only.
- Standard input to standard output only.
- Efficient for the stated constraints.
- Correct handling of all test cases and edge cases implied by the statement.
- Reply with exactly one fenced python code block.

{statement_for(problem)}
"""


def extract_code(text: str) -> str:
    blocks = CODE_BLOCK.findall(text)
    if not blocks:
        raise RuntimeError("no fenced python code block")
    return max(blocks, key=len).strip() + "\n"


def generate_one(problem: dict, model: str, timeout: int, attempts: int) -> dict:
    name = pid(problem)
    dest_dir = OUT / name
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / "solution.py"
    old = dest.read_text(errors="replace") if dest.exists() else ""
    last_error = ""
    for attempt in range(1, attempts + 1):
        with tempfile.NamedTemporaryFile(prefix=f"repair_{name}_", suffix=".md", delete=False) as fh:
            last_msg = Path(fh.name)
        try:
            result = subprocess.run(
                [
                    "codex",
                    "exec",
                    "--model",
                    model,
                    "--cd",
                    str(ROOT),
                    "--sandbox",
                    "read-only",
                    "--dangerously-bypass-approvals-and-sandbox",
                    "--output-last-message",
                    str(last_msg),
                    prompt(problem),
                ],
                cwd=str(ROOT),
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                timeout=timeout,
                check=False,
            )
            if result.returncode != 0:
                detail = (result.stderr.strip() or result.stdout.strip())[-1000:]
                raise RuntimeError(f"codex exit {result.returncode}: {detail}")
            code = extract_code(last_msg.read_text(errors="replace"))
            if BAD_TEXT.search(code):
                raise RuntimeError("generated code still contains generic/header marker")
            if code.strip() == old.strip():
                raise RuntimeError("generated code is unchanged")
            tmp = dest.with_suffix(".repair_tmp.py")
            tmp.write_text(code)
            ok, err = compile_ok(tmp)
            if not ok:
                tmp.unlink(missing_ok=True)
                raise RuntimeError(f"syntax error: {err}")
            tmp.replace(dest)
            record(name, "ok", attempt=attempt, bytes=len(code))
            return {"problem": name, "status": "ok", "attempt": attempt, "bytes": len(code)}
        except Exception as exc:
            last_error = str(exc)
            record(name, "pending", attempt=attempt, error=last_error[:1000])
            time.sleep(min(10 * attempt, 60))
        finally:
            last_msg.unlink(missing_ok=True)
    record(name, "failed", error=last_error[:1000])
    return {"problem": name, "status": "failed", "error": last_error}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default="gpt-5.5")
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--timeout", type=int, default=900)
    parser.add_argument("--attempts", type=int, default=3)
    parser.add_argument("--only", nargs="*")
    parser.add_argument("--limit", type=int)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    problems = load_meta()
    by_pid = {pid(problem): problem for problem in problems}
    targets = args.only or detect_targets(problems)
    if args.limit:
        targets = targets[: args.limit]
    done = set() if args.force else load_done()
    targets = [name for name in targets if name not in done]
    print(f"repair targets: {len(targets)}; workers={args.workers}; model={args.model}", flush=True)
    if not targets:
        return 0

    failed: list[str] = []
    complete = 0
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = [pool.submit(generate_one, by_pid[name], args.model, args.timeout, args.attempts) for name in targets]
        for future in as_completed(futures):
            rec = future.result()
            complete += 1
            if rec["status"] != "ok":
                failed.append(rec["problem"])
            print(f"progress: {complete}/{len(targets)} repaired; {rec['problem']}: {rec['status']}", flush=True)
    if failed:
        print("failed:", " ".join(failed), flush=True)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
